const strings: Record<Lang, Record<string, string>> = { en, ur };

export function t(lang: Lang, key: string): string {
  return strings[lang][key] || strings.en[key] || key;
}

/** Interpolate `{name}` placeholders. */
export function tf(lang: Lang, key: string, vars: Record<string, string | number>): string {
  return t(lang, key).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export function pageTitle(lang: Lang, page: string, role?: string) {
  if (page === 'overview' && role) {
    const keyed = t(lang, `overview_${role}`);
    if (keyed !== `overview_${role}`) return keyed;
  }
  if (page === 'directions' && role === 'SPECIAL_SECRETARY') {
    return t(lang, 'directions_SPECIAL_SECRETARY');
  }
  return t(lang, page);
}

export function roleTitle(lang: Lang, role?: string | null) {
  if (!role) return '';
  const key = `role_${role}_title`;
  const v = t(lang, key);
  return v === key ? role.replace(/_/g, ' ') : v;
}

export function roleBlurb(lang: Lang, role?: string | null) {
  if (!role) return '';
  const key = `role_${role}_blurb`;
  const v = t(lang, key);
  return v === key ? '' : v;
}

/** Localize known seeded staff display names (e.g. Office Speaker → آفس اسپیکر). */
export function personName(lang: Lang, name?: string | null) {
  if (!name) return '';
  const key = `person_${name.replace(/\s+/g, '_')}`;
  const v = t(lang, key);
  return v === key ? name : v;
}

/** Translate API enum / status codes when a dictionary entry exists. */
export function enumLabel(lang: Lang, value?: string | null) {
  if (!value) return '';
  const key = `enum_${value}`;
  const v = t(lang, key);
  if (v !== key) return v;
  return value
    .replace(/_/g, ' ')
    .toLowerCase()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}
